"""
SQLAlchemy ORM model for the ``answer_feedback`` table.

Every assistant answer that a user rates produces one row here. Until this
table existed the eval harness scored only a static curated dataset, so a real
answer that users routinely found wrong produced no signal at all; a row per
(message, user) pair is the smallest unit that changes that.

The rating is an enum rather than free text, and the pair (message, user) is
unique, because the two halves of a feedback loop only close if the values that
reach the column are comparable across users and a user can revise their mind
without stacking a second row beside the first.
"""

from __future__ import annotations

import uuid
from collections.abc import Iterable
from datetime import datetime
from enum import Enum

from sqlalchemy import DateTime, ForeignKey, String, UniqueConstraint, func, select
from sqlalchemy.dialects.postgresql import UUID
from sqlalchemy.ext.asyncio import AsyncSession
from sqlalchemy.orm import Mapped, mapped_column

from app.models.base import Base


class FeedbackRating(str, Enum):
    """Whether a user found an assistant answer helpful.

    Attributes:
        UP: The answer was useful.
        DOWN: The answer was not useful, and may carry a reason and a comment.
    """

    UP = "up"
    DOWN = "down"


class FeedbackCategory(str, Enum):
    """Why a user rated an answer unhelpful.

    Attributes:
        WRONG_ANSWER: The answer contradicts the policy or the facts.
        OUTDATED_POLICY: The answer reflects a superseded policy version.
        UNHELPFUL_TONE: The answer was correct but unusable in its wording.
        MISSING_INFO: The answer left out the part the user needed.
        OTHER: None of the listed reasons fit.
    """

    WRONG_ANSWER = "wrong_answer"
    OUTDATED_POLICY = "outdated_policy"
    UNHELPFUL_TONE = "unhelpful_tone"
    MISSING_INFO = "missing_info"
    OTHER = "other"


class AnswerFeedback(Base):
    """Database model for one user's rating of one assistant answer.

    Attributes:
        id: Primary key UUID.
        message_id: Foreign key to the rated conversation message. The
            constraint is real rather than an indexed column, so a rating can
            never outlive the answer it describes.
        user_id: Foreign key to the user who rated the answer, released with the
            message. A rating no user can claim is not scoped to anyone, so it
            has no reader left to protect and no meaning to keep.
        rating: One of ``FeedbackRating``. Never free text, so rows from
            different users can be counted against each other.
        comment: Optional free-text reason the user typed alongside a rating.
        category: Optional structured reason the user picked, one of
            ``FeedbackCategory``.
        created_at: Timestamp the row was written, generated by the database so
            a row written by a worker with a skewed clock still orders
            correctly against its neighbours.
    """

    __tablename__ = "answer_feedback"

    id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    message_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("conversation_messages.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    user_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("users.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    rating: Mapped[str] = mapped_column(String(16), nullable=False)
    comment: Mapped[str | None] = mapped_column(String(1000), nullable=True)
    category: Mapped[str | None] = mapped_column(String(32), nullable=True)
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=func.now()
    )

    __table_args__ = (
        # A user who changes their mind revises this row instead of inserting a
        # second one, so the pair is the row's identity and every upsert keys on
        # it. Without it two taps on the thumbs button would leave two rows and
        # the counts would be a lie about how many users felt what.
        UniqueConstraint("message_id", "user_id", name="uq_answer_feedback_message_user"),
    )


async def feedback_rows_for_messages(
    session: AsyncSession,
    message_ids: Iterable[uuid.UUID],
) -> dict[uuid.UUID, list[AnswerFeedback]]:
    """Read every rating attached to a set of messages, grouped by message.

    This is the seam a future eval report joins through: a "down"-rated real
    answer is the highest-value eval case a product can get, and the report
    adds one by reading the rated answer's text back from
    ``conversation_messages`` next to these rows. Nothing calls it yet -- the
    join is deliberately not built here -- but it is the whole of the query
    that join needs, kept with the table so the two cannot drift apart.

    Args:
        session: The session performing the read.
        message_ids: The messages whose ratings are wanted.

    Returns:
        dict[uuid.UUID, list[AnswerFeedback]]: One entry per message that has
        at least one rating, in insertion order. Messages with no rating are
        absent rather than mapped to an empty list.
    """
    wanted = list(message_ids)
    if not wanted:
        return {}

    rows = (
        (
            await session.execute(
                select(AnswerFeedback)
                .where(AnswerFeedback.message_id.in_(wanted))
                .order_by(AnswerFeedback.created_at, AnswerFeedback.id)
            )
        )
        .scalars()
        .all()
    )

    grouped: dict[uuid.UUID, list[AnswerFeedback]] = {}
    for row in rows:
        grouped.setdefault(row.message_id, []).append(row)
    return grouped


__all__ = [
    "AnswerFeedback",
    "FeedbackCategory",
    "FeedbackRating",
    "feedback_rows_for_messages",
]
