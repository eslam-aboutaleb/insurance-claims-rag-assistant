"""
SQLAlchemy ORM model for the ``audit_events`` table.

The append-only record of who did what to which entity. ``claims.status`` and
``claim_events`` explain how a claim reached its current state; this table
answers the wider question a regulated insurer is actually asked: who
submitted, signed in, confirmed, withdrew, and rated, and when. The row is
written once and never updated -- an entry in an audit trail that can be
edited is not an audit trail -- so there is no update path anywhere in the
application.

The actor reference is released (``SET NULL``) rather than enforced, matching
``claim_events``: removing an account must not delete the history of what that
account did, and a transition the system performed has no person to name.
"""

from __future__ import annotations

import uuid
from datetime import datetime

from sqlalchemy import DateTime, ForeignKey, Index, String, func
from sqlalchemy.dialects.postgresql import JSONB, UUID
from sqlalchemy.orm import Mapped, mapped_column

from app.models.base import Base


class AuditEvent(Base):
    """Database model for one immutable entry in the audit trail.

    Attributes:
        id: Primary key UUID.
        actor_id: Who performed the action. Nullable so a system or anonymous
            action (a failed sign-in attempt) can be recorded without
            attributing it to a person, and released by the database when the
            actor's account is removed.
        action: The verb that was performed, e.g. ``"auth.signin"``,
            ``"claim.status_changed"``.
        entity_type: The kind of thing acted on, e.g. ``"user"``, ``"claim"``,
            ``"answer_feedback"``.
        entity_id: The identifier of the thing acted on. Human-readable where
            the entity has one (a claim id), a UUID string where it does not.
        before: JSONB snapshot of the fields that changed before the action,
            or None when the action did not overwrite anything.
        after: JSONB snapshot of the fields after the action, or None.
        ip_address: Client IP the action was performed from, when known.
        user_agent: Caller's user agent, when supplied.
        correlation_id: The request's ``X-Request-ID``, so an entry can be
            read beside its own line in the application log. Null when the
            action ran outside a request (a startup job, a direct call).
        created_at: Timestamp the row was written, generated by the database so
            an entry written by a worker with a skewed clock still orders
            correctly against its neighbours.
    """

    __tablename__ = "audit_events"

    id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    actor_id: Mapped[uuid.UUID | None] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("users.id", ondelete="SET NULL"),
        nullable=True,
        index=True,
    )
    action: Mapped[str] = mapped_column(String(64), nullable=False, index=True)
    entity_type: Mapped[str] = mapped_column(String(64), nullable=False)
    entity_id: Mapped[str | None] = mapped_column(String(128), nullable=True)
    before: Mapped[dict | None] = mapped_column(JSONB, nullable=True)
    after: Mapped[dict | None] = mapped_column(JSONB, nullable=True)
    ip_address: Mapped[str | None] = mapped_column(String(64), nullable=True)
    user_agent: Mapped[str | None] = mapped_column(String(512), nullable=True)
    correlation_id: Mapped[str | None] = mapped_column(String(64), nullable=True)
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=func.now()
    )

    __table_args__ = (
        # The admin trail filters on the pair (entity type, entity id) -- "show
        # me everything that ever happened to this claim" -- so both columns
        # belong in one index rather than two.
        Index("ix_audit_events_entity", "entity_type", "entity_id"),
        # The listing is paged by newest first, so the ordering column is
        # indexed for the same reason.
        Index("ix_audit_events_created_at", "created_at"),
    )


__all__ = ["AuditEvent"]
