"""In-process aggregates for LLM cost, tool latency, and limiter rejections.

Events are held in bounded deques rather than plain counters so one store can
answer both "over this window" and "since boot", and so a process that stays up
for weeks cannot grow the store without limit. The store is deliberately
synchronous and in-process: producing telemetry must never be able to block or
fail the request that is being measured.
"""

from __future__ import annotations

import logging
import threading
import time
from collections import Counter, deque
from dataclasses import dataclass
from typing import Any

from app.observability.request_context import get_request_id

logger = logging.getLogger(__name__)

# One hour is long enough to make the unit economics of a support conversation
# visible and short enough that the deques stay meaningful for the operators
# reading the percentiles.
DEFAULT_WINDOW_SECONDS = 3600.0

# Bounded so a chat storm cannot exhaust memory through the telemetry path. Older
# events are dropped, which costs history rather than availability.
_MAX_EVENTS = 2000

_UNKNOWN_MODEL = "unknown"


@dataclass(frozen=True)
class LlmCall:
    """One model completion, successful or not.

    Attributes:
        timestamp: Unix time the call finished.
        model: Model identifier reported by the provider.
        prompt_tokens: Input tokens billed for the call.
        completion_tokens: Output tokens generated by the call.
        cost_usd: Dollar cost of the call as computed by ``litellm.completion_cost``.
        latency_seconds: Wall-clock duration of the call.
        success: ``False`` when the call raised before returning.
        request_id: Correlation id of the request that triggered the call.
        error: Exception representation when ``success`` is ``False``.
    """

    timestamp: float
    model: str
    prompt_tokens: int
    completion_tokens: int
    cost_usd: float
    latency_seconds: float
    success: bool
    request_id: str
    error: str = ""


@dataclass(frozen=True)
class ToolCall:
    """One agent tool invocation.

    Attributes:
        timestamp: Unix time the invocation finished.
        name: Registered tool name, e.g. ``query_policy``.
        latency_seconds: Wall-clock duration of the invocation.
        success: ``False`` when the tool raised.
        request_id: Correlation id of the request that triggered the invocation.
        error: Exception representation when ``success`` is ``False``.
    """

    timestamp: float
    name: str
    latency_seconds: float
    success: bool
    request_id: str
    error: str = ""


@dataclass(frozen=True)
class LimiterRejection:
    """One request refused by the rate limiter.

    Attributes:
        timestamp: Unix time the rejection was recorded.
        route: Request path that was refused.
        request_id: Correlation id of the refused request.
    """

    timestamp: float
    route: str
    request_id: str


def _mean_milliseconds(latencies: list[float]) -> float:
    """Return the average of ``latencies`` in milliseconds, rounded for display."""
    if not latencies:
        return 0.0
    return round(sum(latencies) * 1000.0 / len(latencies), 3)


def _count_by(values: list[str]) -> dict[str, int]:
    """Count ``values`` and return them sorted so output is stable across calls."""
    return dict(sorted(Counter(values).items()))


def _summarise_llm(calls: list[LlmCall]) -> dict[str, Any]:
    """Aggregate LLM calls into the shape the health endpoint reports.

    Args:
        calls: Calls inside the reporting window.

    Returns:
        dict[str, Any]: Call counts, token and dollar totals, and average latency.
    """
    return {
        "call_count": len(calls),
        "error_count": sum(1 for call in calls if not call.success),
        "prompt_tokens": sum(call.prompt_tokens for call in calls),
        "completion_tokens": sum(call.completion_tokens for call in calls),
        "total_cost_usd": round(sum(call.cost_usd for call in calls), 6),
        "avg_latency_ms": _mean_milliseconds([call.latency_seconds for call in calls]),
        "calls_by_model": _count_by([call.model for call in calls]),
    }


def _summarise_tools(calls: list[ToolCall]) -> dict[str, Any]:
    """Aggregate tool invocations into per-tool counts and average latency.

    Args:
        calls: Invocations inside the reporting window.

    Returns:
        dict[str, Any]: Totals plus one entry per tool, ordered by tool name.
    """
    grouped: dict[str, list[ToolCall]] = {}
    for call in calls:
        grouped.setdefault(call.name, []).append(call)
    by_tool = [
        {
            "name": name,
            "call_count": len(grouped[name]),
            "error_count": sum(1 for call in grouped[name] if not call.success),
            "avg_latency_ms": _mean_milliseconds([call.latency_seconds for call in grouped[name]]),
        }
        for name in sorted(grouped)
    ]
    return {
        "total_calls": len(calls),
        "error_count": sum(1 for call in calls if not call.success),
        "by_tool": by_tool,
    }


def _summarise_rejections(rejections: list[LimiterRejection]) -> dict[str, Any]:
    """Aggregate limiter rejections into per-route counts.

    Args:
        rejections: Rejections inside the reporting window.

    Returns:
        dict[str, Any]: Total rejections plus a per-route breakdown.
    """
    return {
        "rejections": len(rejections),
        "by_route": _count_by([rejection.route for rejection in rejections]),
    }


class MetricsRegistry:
    """Thread-safe, bounded store of telemetry events."""

    def __init__(self, max_events: int = _MAX_EVENTS) -> None:
        """Initialise the registry.

        Args:
            max_events: Number of events retained per event type.
        """
        self._llm_calls: deque[LlmCall] = deque(maxlen=max_events)
        self._tool_calls: deque[ToolCall] = deque(maxlen=max_events)
        self._limiter_rejections: deque[LimiterRejection] = deque(maxlen=max_events)
        # LiteLLM fires its logging hooks from its own worker threads, so the
        # store cannot assume a single-threaded event loop.
        self._lock = threading.Lock()

    def record_llm_call(self, call: LlmCall) -> None:
        """Append one model completion to the store.

        Args:
            call: The completion to record.
        """
        with self._lock:
            self._llm_calls.append(call)
        logger.debug(
            "LLM call recorded",
            extra={
                "event": "llm_call",
                "model": call.model,
                "prompt_tokens": call.prompt_tokens,
                "completion_tokens": call.completion_tokens,
                "cost_usd": call.cost_usd,
                "latency_seconds": call.latency_seconds,
                "success": call.success,
            },
        )

    def record_tool_call(self, call: ToolCall) -> None:
        """Append one tool invocation to the store.

        Args:
            call: The invocation to record.
        """
        with self._lock:
            self._tool_calls.append(call)
        logger.debug(
            "Tool call recorded",
            extra={
                "event": "tool_call",
                "tool": call.name,
                "latency_seconds": call.latency_seconds,
                "success": call.success,
            },
        )

    def record_limiter_rejection(self, rejection: LimiterRejection) -> None:
        """Append one rate-limit rejection to the store.

        Args:
            rejection: The rejection to record.
        """
        with self._lock:
            self._limiter_rejections.append(rejection)
        logger.debug(
            "Rate limit rejection recorded",
            extra={
                "event": "rate_limit_rejection",
                "route": rejection.route,
            },
        )

    def snapshot(self, window_seconds: float = DEFAULT_WINDOW_SECONDS) -> dict[str, Any]:
        """Summarise the events recorded in the last ``window_seconds``.

        Args:
            window_seconds: Length of the reporting window.

        Returns:
            dict[str, Any]: Window length plus LLM, tool, and limiter summaries.
        """
        cutoff = time.time() - window_seconds
        with self._lock:
            llm_calls = [call for call in self._llm_calls if call.timestamp >= cutoff]
            tool_calls = [call for call in self._tool_calls if call.timestamp >= cutoff]
            rejections = [
                rejection for rejection in self._limiter_rejections if rejection.timestamp >= cutoff
            ]
        return {
            "window_seconds": window_seconds,
            "llm": {**_summarise_llm(llm_calls), "window_seconds": window_seconds},
            "tools": {**_summarise_tools(tool_calls), "window_seconds": window_seconds},
            "rate_limits": {**_summarise_rejections(rejections), "window_seconds": window_seconds},
        }

    def reset(self) -> None:
        """Drop every recorded event."""
        with self._lock:
            self._llm_calls.clear()
            self._tool_calls.clear()
            self._limiter_rejections.clear()


_registry = MetricsRegistry()


def get_metrics() -> MetricsRegistry:
    """Return the process-wide metrics registry."""
    return _registry


def reset_metrics() -> None:
    """Clear the process-wide registry, used by tests to isolate counts."""
    _registry.reset()


def build_llm_call(  # noqa: PLR0913 -- one field per billable reading of a call
    *,
    model: str = _UNKNOWN_MODEL,
    prompt_tokens: int = 0,
    completion_tokens: int = 0,
    cost_usd: float = 0.0,
    latency_seconds: float = 0.0,
    success: bool = True,
    error: str = "",
) -> LlmCall:
    """Create an :class:`LlmCall` stamped with the current time and request id.

    Args:
        model: Model identifier reported by the provider.
        prompt_tokens: Input tokens billed for the call.
        completion_tokens: Output tokens generated by the call.
        cost_usd: Dollar cost of the call.
        latency_seconds: Wall-clock duration of the call.
        success: ``False`` when the call raised before returning.
        error: Exception representation when ``success`` is ``False``.

    Returns:
        LlmCall: The event ready to hand to :meth:`MetricsRegistry.record_llm_call`.
    """
    return LlmCall(
        timestamp=time.time(),
        model=model,
        prompt_tokens=prompt_tokens,
        completion_tokens=completion_tokens,
        cost_usd=cost_usd,
        latency_seconds=latency_seconds,
        success=success,
        request_id=get_request_id() or "-",
        error=error,
    )


def build_tool_call(
    *,
    name: str,
    latency_seconds: float,
    success: bool = True,
    error: str = "",
) -> ToolCall:
    """Create a :class:`ToolCall` stamped with the current time and request id.

    Args:
        name: Registered tool name.
        latency_seconds: Wall-clock duration of the invocation.
        success: ``False`` when the tool raised.
        error: Exception representation when ``success`` is ``False``.

    Returns:
        ToolCall: The event ready to hand to :meth:`MetricsRegistry.record_tool_call`.
    """
    return ToolCall(
        timestamp=time.time(),
        name=name,
        latency_seconds=latency_seconds,
        success=success,
        request_id=get_request_id() or "-",
        error=error,
    )
